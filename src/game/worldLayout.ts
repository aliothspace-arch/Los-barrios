export function buildStaticColliders(): ColliderAABB[] {
  const colliders: ColliderAABB[] = [];

  for (const b of BUILDINGS) {
    const cos = Math.abs(Math.cos(b.rotY));
    const sin = Math.abs(Math.sin(b.rotY));
    const halfW = (b.w * cos + b.d * sin) * 0.5;
    const halfD = (b.w * sin + b.d * cos) * 0.5;
    colliders.push({
      id: b.id,
      minX: b.x - halfW,
      maxX: b.x + halfW,
      minZ: b.z - halfD,
      maxZ: b.z + halfD,
      height: b.h,
      category: 'building',
    });
  }

  for (let i = 0; i < PALM_POSITIONS.length; i++) {
    const p = PALM_POSITIONS[i];
    colliders.push({
      id: `palm_${i}`,
      minX: p.x - 0.52,
      maxX: p.x + 0.52,
      minZ: p.z - 0.52,
      maxZ: p.z + 0.52,
      height: 12,
      category: 'tree',
    });
  }

  for (let i = 0; i < SHADE_TREE_POSITIONS.length; i++) {
    const t = SHADE_TREE_POSITIONS[i];
    colliders.push({
      id: `shade_tree_${i}`,
      minX: t.x - 0.55,
      maxX: t.x + 0.55,
      minZ: t.z - 0.55,
      maxZ: t.z + 0.55,
      height: 8,
      category: 'tree',
    });
  }

  return colliders;
}

export function getDistrictName(x: number, z: number): string {
  if (z < -130) return 'VINEWOOD BOULEVARD';
  if (z < -72) return 'DOWNTOWN LOS SANTOS';
  if (z > 90) return 'OCEAN BEACH';
  if (x > 105) return 'LAS COLINAS';
  if (x < -105) return 'RODEO PLAZA';
  if (x > 46 && z > -24) return 'EAST LOS SANTOS';
  if (x < -46 && z > -24) return 'COMMERCE';
  if (z > 36) return 'IDLEWOOD';
  if (Math.hypot(x - CUL_DE_SAC.x, z - CUL_DE_SAC.z) < 30) return 'GROVE STREET';
  return 'GANTON';
}
